    public static String getLang(Context c) {
        return RUSSIAN.getLanguage();
    }

    public static Locale locale(Context c) {
        return RUSSIAN;
    }

    public static String t(Context c, String key) {
        if (key == null) return "";
        String translation = RUSSIAN_STRINGS.get(key);
        if (translation != null) return translation;
        if (key.endsWith("% used · Recent Apps") || key.endsWith("% used · Clean")) {
            int suffix = key.indexOf('%');
            return key.substring(0, suffix) + t(c, key.substring(suffix));
        }
        if (key.endsWith(" min left")) {
            return key.substring(0, key.length() - " min left".length()) + " мин осталось";
        }
        if (key.startsWith("Move ")) return "Переместить " + key.substring("Move ".length());
        if (key.startsWith("Switch to ")) return "Переключиться на " + key.substring("Switch to ".length());
        if (key.startsWith("Done (") && key.endsWith(" apps disabled)")) {
            return "Готово. Отключено приложений: "
                    + key.substring("Done (".length(), key.length() - " apps disabled)".length());
        }
        if (key.startsWith("Not done (") && key.endsWith(" disabled)")) {
            return "Отключено " + key.substring("Not done (".length(), key.length() - " disabled)".length());
        }
        return key;
    }

    public static String formatSceneDate(Context c, Date date) {
        return new SimpleDateFormat("EEEE, d MMMM", RUSSIAN).format(date);
    }

    public static String profileName(Context c, String name) {
        if (name == null) return "";
        if (name.equals("Default") || name.equals("Varsayılan")) return "По умолчанию";
        if (name.equals("Kids") || name.equals("Çocuklar")) return "Дети";
        for (String prefix : new String[]{"Person ", "Kişi ", "Profile ", "Profil "}) {
            if (name.startsWith(prefix) && name.substring(prefix.length()).matches("[0-9]+")) {
                return "Профиль " + name.substring(prefix.length());
            }
        }
        return name;
    }
